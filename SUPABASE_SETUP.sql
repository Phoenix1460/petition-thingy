-- Run this once in your Supabase project's SQL Editor before using the petition.
-- The site uses the publishable key in the browser, so row-level security is essential.

create table if not exists public.signatures (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  created_at timestamptz not null default now()
);

create unique index if not exists signatures_name_unique
  on public.signatures (lower(btrim(name)));

alter table public.signatures enable row level security;

grant select, insert on public.signatures to anon;
grant usage, select on sequence public.signatures_id_seq to anon;

drop policy if exists "Anyone can view petition signatures" on public.signatures;
create policy "Anyone can view petition signatures"
  on public.signatures for select to anon
  using (true);

drop policy if exists "Anyone can add a petition signature" on public.signatures;
create policy "Anyone can add a petition signature"
  on public.signatures for insert to anon
  with check (char_length(btrim(name)) between 1 and 80);
